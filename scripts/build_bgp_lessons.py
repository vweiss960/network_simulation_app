#!/usr/bin/env python3
"""Build the starting topologies of the BGP lessons that follow bgp-sp-core.

    python3 scripts/build_bgp_lessons.py

The BGP lessons share one topology. bgp-path-selection-policy and
bgp-addpaths-pic start where bgp-sp-core ends, so their topology.yaml is
bgp-sp-core's with every device's starting config extended by that lesson's
reference solutions (in task order). Re-run after editing bgp-sp-core's
topology or solutions, then bump the dependent lessons' version.
"""
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1] / "curriculum" / "lessons"
BASE = "bgp-sp-core"
DEPENDENTS = {
    "bgp-path-selection-policy": {
        "name": "BGP path selection and routing policy",
        "description": "AS 65000 from the BGP core lesson, fully built: iBGP through the route reflector, "
                       "eBGP to the customer and both upstreams. Now decide which paths win.",
    },
    "bgp-addpaths-pic": {
        "name": "BGP additional paths and PIC",
        "description": "AS 65000 from the BGP core lesson, fully built — with two exits to the Internet "
                       "that the route reflector hides from its clients.",
    },
}


class _Block(str):
    pass


yaml.SafeDumper.add_representer(_Block, lambda d, s: d.represent_scalar("tag:yaml.org,2002:str", s, style="|"))


def main():
    topo = yaml.safe_load((ROOT / BASE / "topology.yaml").read_text())
    tasks = yaml.safe_load((ROOT / BASE / "tasks.yaml").read_text())
    added: dict[str, list[str]] = {}
    for t in tasks:
        for dev, cfg in (t.get("solution") or {}).items():
            lines = [l for l in cfg.splitlines() if not l.strip().startswith("do ")]   # exec commands
            added.setdefault(dev, []).append("\n".join(lines).rstrip() + "\n")
    for slug, meta in DEPENDENTS.items():
        out = {"name": meta["name"], "description": meta["description"], "nodes": [], "links": topo["links"],
               "annotations": topo["annotations"]}
        for n in topo["nodes"]:
            n = dict(n)
            cfg = (n.get("startup_config") or "").rstrip() + "\n"
            for block in added.get(n["name"], []):
                cfg += "!\n" + block
            n["startup_config"] = _Block(cfg)
            out["nodes"].append(n)
        text = yaml.safe_dump(out, sort_keys=False, allow_unicode=True, width=200, default_flow_style=None)
        header = (f"# Generated by scripts/build_bgp_lessons.py from {BASE}: its topology plus its\n"
                  f"# reference solutions. Edit {BASE} and re-run instead of editing this file.\n")
        (ROOT / slug).mkdir(exist_ok=True)
        (ROOT / slug / "topology.yaml").write_text(header + text)
        print(f"wrote {slug}/topology.yaml")


if __name__ == "__main__":
    main()
