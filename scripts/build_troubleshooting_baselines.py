#!/usr/bin/env python3
"""Build the healthy baseline topology of each troubleshooting scenario from
a lesson whose reference solutions were verified on live devices.

    python3 scripts/build_troubleshooting_baselines.py

baseline = the lesson's topology + every task's reference solution appended
to each device's starting config (`do …` exec lines dropped), with the
canvas annotations and device notes removed — a troubleshooting lab shows
no design. Re-run after editing the source lesson, then bump the scenario's
version.
"""
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1] / "curriculum"
SCENARIOS = {
    "sp-core-isis-bgp": {
        "lesson": "bgp-sp-core",
        "name": "Service provider core — IS-IS and BGP",
        "description": "AS 65000: an IS-IS core with a BGP route reflector, a customer and two upstream providers.",
        "drop_lines": [],
    },
    "ospf-multiarea": {
        "lesson": "ospf-xr-multiarea-area-types",
        "name": "Multi-area OSPFv2 and OSPFv3",
        "description": "A three-router OSPF backbone with a totally stubby area and an NSSA, dual-stacked.",
        # The lesson's starting fault and its fix: the healthy baseline has neither.
        "drop_lines": ["ip ospf hello-interval 5", "no ip ospf hello-interval"],
    },
}


class _Block(str):
    pass


yaml.SafeDumper.add_representer(_Block, lambda d, s: d.represent_scalar("tag:yaml.org,2002:str", s, style="|"))


def build(slug: str, spec: dict) -> None:
    lesson = ROOT / "lessons" / spec["lesson"]
    topo = yaml.safe_load((lesson / "topology.yaml").read_text())
    tasks = yaml.safe_load((lesson / "tasks.yaml").read_text())
    keep = lambda l: not l.strip().startswith("do ") and l.strip() not in spec["drop_lines"]  # noqa: E731
    added: dict[str, list[str]] = {}
    for t in tasks:
        for dev, cfg in (t.get("solution") or {}).items():
            added.setdefault(dev, []).append("\n".join(l for l in cfg.splitlines() if keep(l)).rstrip() + "\n")
    nodes = []
    for n in topo["nodes"]:
        n = {k: v for k, v in n.items() if k != "notes"}
        cfg = "\n".join(l for l in (n.get("startup_config") or "").splitlines() if keep(l)).rstrip() + "\n"
        for block in added.get(n["name"], []):
            cfg += "!\n" + block
        n["startup_config"] = _Block(cfg)
        nodes.append(n)
    # Link labels name protocols / areas: keep only the endpoints.
    links = [row[:4] for row in topo["links"]]
    out = {"name": spec["name"], "description": spec["description"], "nodes": nodes, "links": links, "annotations": []}
    header = (f"# Generated by scripts/build_troubleshooting_baselines.py from the lesson {spec['lesson']}:\n"
              f"# its topology plus every reference solution. Re-run instead of editing this file.\n")
    d = ROOT / "troubleshooting" / slug
    d.mkdir(parents=True, exist_ok=True)
    (d / "topology.yaml").write_text(header + yaml.safe_dump(out, sort_keys=False, allow_unicode=True, width=200,
                                                              default_flow_style=None))
    print(f"wrote troubleshooting/{slug}/topology.yaml")


if __name__ == "__main__":
    for slug, spec in SCENARIOS.items():
        build(slug, spec)
